    public sealed class GitHubReleaseAsset
    {
        [JsonPropertyName("name")]
        public string Name { get; set; } = string.Empty;

        [JsonPropertyName("browser_download_url")]
        public string BrowserDownloadUrl { get; set; } = string.Empty;

        [JsonPropertyName("size")]
        public long Size { get; set; }

        [JsonPropertyName("digest")]
        public string Digest { get; set; } = string.Empty;
    }

    /// <summary>
    /// ISSUE_15: KeyPulse used to report version 1.0.0.0 for every build ever released and never
    /// looked for a newer one. This deserializes full release metadata including notes and assets.
    /// </summary>
    public sealed class GitHubRelease
    {
        [JsonPropertyName("tag_name")]
        public string TagName { get; set; } = string.Empty;

        [JsonPropertyName("name")]
        public string Name { get; set; } = string.Empty;

        [JsonPropertyName("html_url")]
        public string HtmlUrl { get; set; } = string.Empty;

        [JsonPropertyName("body")]
        public string Body { get; set; } = string.Empty;

        [JsonPropertyName("draft")]
        public bool Draft { get; set; }

        [JsonPropertyName("prerelease")]
        public bool Prerelease { get; set; }

        [JsonPropertyName("assets")]
        public List<GitHubReleaseAsset> Assets { get; set; } = new();
    }

    public readonly struct UpdateCheckResult
    {
        public bool Succeeded { get; init; }
        public bool UpdateAvailable { get; init; }
        public string LatestVersion { get; init; }
        public string Message { get; init; }
        public string? LocalInstallerPath { get; init; }
        public string? DownloadUrl { get; init; }
        public string? ReleaseNotes { get; init; }
        public long AssetSizeBytes { get; init; }
        public string? ExpectedSha256 { get; init; }
    }

    public static class UpdateChecker
    {
        private static readonly HttpClient Client = CreateClient();
        private static readonly HttpClient DownloadClient = CreateDownloadClient();

        private static HttpClient CreateClient()
        {
            var client = new HttpClient { Timeout = TimeSpan.FromSeconds(30) };
            client.DefaultRequestHeaders.Add("User-Agent", "KeyPulse-UpdateCheck");
            client.DefaultRequestHeaders.Add("Accept", "application/vnd.github+json");
            return client;
        }

        private static HttpClient CreateDownloadClient()
        {
            var client = new HttpClient { Timeout = TimeSpan.FromMinutes(15) };
            client.DefaultRequestHeaders.Add("User-Agent", "KeyPulse-UpdateDownload");
            return client;
        }

        /// <summary>
        /// DEVUPDATE_01: In dev mode, inspect local .\compiled\KeyPulse.exe instead of querying GitHub.
        /// </summary>
        public static async Task<UpdateCheckResult> CheckAsync(string channel = "Stable", CancellationToken cancellationToken = default)
        {
            try
            {
                var devUpdateSource = Environment.GetEnvironmentVariable("KEYPULSE_DEV_UPDATE_SOURCE");
                if (!string.IsNullOrWhiteSpace(devUpdateSource))
                {
                    var localExe = Path.Combine(devUpdateSource.Trim(), "compiled", "KeyPulse.exe");
                    if (!File.Exists(localExe))
                    {
                        return new UpdateCheckResult
                        {
                            Succeeded = false,
                            Message = $"Dev update source active, but '{localExe}' does not exist yet. Run .\\dev_build.cmd first."
                        };
                    }

                    var info = System.Diagnostics.FileVersionInfo.GetVersionInfo(localExe);
                    var rawVer = info.FileVersion ?? "unknown";
                    var latestLocal = rawVer.EndsWith(".0", StringComparison.Ordinal) && rawVer.Count(c => c == '.') == 3
                        ? rawVer.Substring(0, rawVer.Length - 2)
                        : rawVer;
                    var currentVer = Program.AppVersion;

                    return new UpdateCheckResult
                    {
                        Succeeded = true,
                        UpdateAvailable = CompareVersions(latestLocal, currentVer) > 0,
                        LatestVersion = latestLocal,
                        LocalInstallerPath = localExe,
                        DownloadUrl = null,
                        ReleaseNotes = "Local developer test build generated by .\\dev_build.cmd.",
                        AssetSizeBytes = new FileInfo(localExe).Length,
                        ExpectedSha256 = null,
                        Message = string.Empty
                    };
                }

                var isBeta = string.Equals(channel, "Beta", StringComparison.OrdinalIgnoreCase);
                var apiUrl = isBeta
                    ? $"https://api.github.com/repos/{Program.RepositorySlug}/releases"
                    : Program.LatestReleaseApiUrl;

                using var response = await Client.GetAsync(apiUrl, cancellationToken);
                if (!response.IsSuccessStatusCode)
                {
                    return new UpdateCheckResult
                    {
                        Succeeded = false,
                        Message = $"GitHub answered {(int)response.StatusCode}."
                    };
                }

                var json = await response.Content.ReadAsStringAsync(cancellationToken);
                GitHubRelease? release = null;
                if (isBeta)
                {
                    var releases = System.Text.Json.JsonSerializer.Deserialize(json, AppConfigJsonContext.Default.ListGitHubRelease);
                    release = releases?.FirstOrDefault(r => !r.Draft);
                }
                else
                {
                    release = System.Text.Json.JsonSerializer.Deserialize(json, AppConfigJsonContext.Default.GitHubRelease);
                }

                if (release == null || string.IsNullOrWhiteSpace(release.TagName))
                {
                    return new UpdateCheckResult { Succeeded = false, Message = "GitHub did not name a valid release." };
                }

                var latest = release.TagName.TrimStart('v', 'V');
                var current = Program.AppVersion;

                var exeAsset = release.Assets?.FirstOrDefault(a => string.Equals(a.Name, "KeyPulse.exe", StringComparison.OrdinalIgnoreCase));
                var downloadUrl = exeAsset?.BrowserDownloadUrl ?? $"https://github.com/{Program.RepositorySlug}/releases/download/{release.TagName}/KeyPulse.exe";
                var assetSize = exeAsset?.Size ?? 0;

                string? expectedSha256 = null;
                if (!string.IsNullOrWhiteSpace(exeAsset?.Digest))
                {
                    var d = exeAsset.Digest.Trim();
                    expectedSha256 = d.StartsWith("sha256:", StringComparison.OrdinalIgnoreCase) ? d.Substring(7) : d;
                }
                if (string.IsNullOrWhiteSpace(expectedSha256) && !string.IsNullOrWhiteSpace(release.Body))
                {
                    var m = System.Text.RegularExpressions.Regex.Match(release.Body, @"(?:SHA-?256|hash):\s*`?([a-fA-F0-9]{64})`?", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
                    if (m.Success)
                    {
                        expectedSha256 = m.Groups[1].Value.ToLowerInvariant();
                    }
                }
                if (string.IsNullOrWhiteSpace(expectedSha256) && release.Assets != null)
                {
                    var sumsAsset = release.Assets.FirstOrDefault(a => string.Equals(a.Name, "SHA256SUMS.txt", StringComparison.OrdinalIgnoreCase));
                    if (sumsAsset != null && !string.IsNullOrWhiteSpace(sumsAsset.BrowserDownloadUrl))
                    {
                        try
                        {
                            using var sumsResp = await Client.GetAsync(sumsAsset.BrowserDownloadUrl, cancellationToken);
                            if (sumsResp.IsSuccessStatusCode)
                            {
                                var sumsText = await sumsResp.Content.ReadAsStringAsync(cancellationToken);
                                var sm = System.Text.RegularExpressions.Regex.Match(sumsText, @"([a-fA-F0-9]{64})\s+\*?KeyPulse\.exe", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
                                if (sm.Success)
                                {
                                    expectedSha256 = sm.Groups[1].Value.ToLowerInvariant();
                                }
                            }
                        }
                        catch { }
                    }
                }

                return new UpdateCheckResult
                {
                    Succeeded = true,
                    UpdateAvailable = CompareVersions(latest, current) > 0,
                    LatestVersion = latest,
                    DownloadUrl = downloadUrl,
                    ReleaseNotes = string.IsNullOrWhiteSpace(release.Body) ? "No release notes provided." : release.Body,
                    AssetSizeBytes = assetSize,
                    ExpectedSha256 = expectedSha256,
                    Message = string.Empty
                };
            }
            catch (Exception ex)
            {
                Program.LogDebug("Update check failed: " + ex.Message);
                return new UpdateCheckResult { Succeeded = false, Message = ex.Message };
            }
        }

        /// <summary>
        /// Downloads the release executable to a staging path with cryptographic integrity verification,
        /// Authenticode signature validation, HTTP Range resumable transfers, and automatic reconnection retries.
        /// </summary>
        public static async Task<(bool Succeeded, string Message, string? StagedExePath)> DownloadUpdateAsync(
            string downloadUrl,
            string targetVersion,
            string? expectedSha256 = null,
            IProgress<double>? progress = null,
            CancellationToken cancellationToken = default)
        {
            try
            {
                var updatesDir = Path.Combine(
                    Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                    Program.IsDevMode ? "KeyPulse_DEV" : "KeyPulse",
                    "updates");
                try
                {
                    Directory.CreateDirectory(updatesDir);
                    var drive = new DriveInfo(Path.GetPathRoot(updatesDir) ?? "C:\\");
                    if (drive.AvailableFreeSpace < 150 * 1024 * 1024)
                    {
                        return (false, "Insufficient free disk space in updates directory (< 150 MB free).", null);
                    }
                }
                catch { }

                var tempPath = Path.Combine(updatesDir, $"KeyPulse_Update_{targetVersion}.exe");
                var partialPath = tempPath + ".download";

                const int maxRetries = 3;
                bool downloadComplete = false;
                string downloadError = string.Empty;

                for (int attempt = 1; attempt <= maxRetries && !downloadComplete; attempt++)
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    long existingBytes = 0;
                    if (File.Exists(partialPath))
                    {
                        try { existingBytes = new FileInfo(partialPath).Length; } catch { existingBytes = 0; }
                    }

                    try
                    {
                        using var request = new HttpRequestMessage(HttpMethod.Get, downloadUrl);
                        if (existingBytes > 0)
                        {
                            request.Headers.Range = new System.Net.Http.Headers.RangeHeaderValue(existingBytes, null);
                        }

                        using var response = await DownloadClient.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, cancellationToken);
                        bool isPartial = response.StatusCode == System.Net.HttpStatusCode.PartialContent;

                        if (!response.IsSuccessStatusCode && !isPartial)
                        {
                            if (response.StatusCode == System.Net.HttpStatusCode.RequestedRangeNotSatisfiable)
                            {
                                try { File.Delete(partialPath); } catch { }
                                existingBytes = 0;
                                continue;
                            }
                            response.EnsureSuccessStatusCode();
                        }

                        var fileMode = (isPartial && existingBytes > 0) ? FileMode.Append : FileMode.Create;
                        if (!isPartial && existingBytes > 0)
                        {
                            existingBytes = 0;
                        }

                        var totalBytes = response.Content.Headers.ContentLength.HasValue
                            ? response.Content.Headers.ContentLength.Value + existingBytes
                            : -1L;

                        using (var contentStream = await response.Content.ReadAsStreamAsync(cancellationToken))
                        using (var fileStream = new FileStream(partialPath, fileMode, FileAccess.Write, FileShare.None, 81920, true))
                        {
                            var buffer = new byte[81920];
                            long currentTotal = existingBytes;
                            int bytesRead;

                            while ((bytesRead = await contentStream.ReadAsync(buffer, 0, buffer.Length, cancellationToken)) > 0)
                            {
                                await fileStream.WriteAsync(buffer, 0, bytesRead, cancellationToken);
                                currentTotal += bytesRead;

                                if (totalBytes > 0 && progress != null)
                                {
                                    var ratio = (double)currentTotal / totalBytes;
                                    progress.Report(Math.Clamp(ratio, 0.0, 1.0));
                                }
                            }

                            if (totalBytes > 0 && currentTotal != totalBytes)
                            {
                                throw new IOException($"Incomplete download stream: received {currentTotal} of {totalBytes} bytes.");
                            }

                            if (currentTotal < 5 * 1024 * 1024)
                            {
                                throw new IOException($"Downloaded file is too small to be a valid KeyPulse release ({currentTotal} bytes).");
                            }
                        }

                        downloadComplete = true;
                    }
                    catch (OperationCanceledException)
                    {
                        throw;
                    }
                    catch (Exception ex)
                    {
                        downloadError = ex.Message;
                        if (attempt < maxRetries)
                        {
                            await Task.Delay(1000 * attempt, cancellationToken);
                        }
                    }
                }

                if (!downloadComplete)
                {
                    try { File.Delete(partialPath); } catch { }
                    return (false, $"Download interrupted after {maxRetries} attempts: {downloadError}", null);
                }

                using (var verifyStream = new FileStream(partialPath, FileMode.Open, FileAccess.Read, FileShare.Read))
                {
                    var header = new byte[2];
                    if (verifyStream.Read(header, 0, 2) != 2 || header[0] != 'M' || header[1] != 'Z')
                    {
                        verifyStream.Dispose();
                        try { File.Delete(partialPath); } catch { }
                        return (false, "Downloaded file is corrupted (invalid Windows PE executable header).", null);
                    }

                    verifyStream.Position = 0;
                    using var sha = SHA256.Create();
                    var hashBytes = sha.ComputeHash(verifyStream);
                    var computedHash = BitConverter.ToString(hashBytes).Replace("-", "").ToLowerInvariant();

                    if (!string.IsNullOrWhiteSpace(expectedSha256))
                    {
                        var cleanExpected = expectedSha256.Trim().ToLowerInvariant();
                        if (!string.Equals(computedHash, cleanExpected, StringComparison.OrdinalIgnoreCase))
                        {
                            verifyStream.Dispose();
                            try { File.Delete(partialPath); } catch { }
                            return (false, $"Cryptographic SHA-256 verification failed (expected {cleanExpected}, got {computedHash}). Update rejected.", null);
                        }
                    }
                }

                try
                {
#pragma warning disable SYSLIB0057
                    using var cert = System.Security.Cryptography.X509Certificates.X509Certificate2.CreateFromSignedFile(partialPath);
#pragma warning restore SYSLIB0057
                    if (cert != null && !string.IsNullOrWhiteSpace(cert.Subject) && !cert.Subject.Contains("KeyPulse", StringComparison.OrdinalIgnoreCase))
                    {
                        try { File.Delete(partialPath); } catch { }
                        return (false, "Downloaded executable signature is untrusted (signer does not match KeyPulse). Update rejected.", null);
                    }
                }
                catch (System.Security.Cryptography.CryptographicException)
                {
                    // No embedded signature: SHA-256 hash check serves as primary integrity check
                }

                if (File.Exists(tempPath))
                {
                    try { File.Delete(tempPath); } catch { }
                }

                File.Move(partialPath, tempPath, true);
                progress?.Report(1.0);

                return (true, string.Empty, tempPath);
            }
            catch (OperationCanceledException)
            {
                return (false, "Update download was canceled.", null);
            }
            catch (Exception ex)
            {
                Program.LogCrash("Update download failed: " + ex.Message);
                return (false, ex.Message, null);
            }
        }

        /// <summary>
        /// Compares versions following SemVer 2.0 rules: numeric components first, with normal
        /// releases having higher precedence than pre-releases of the same base version.
        /// Returns >0 when left is newer, <0 when right is newer, and 0 when equal.
        /// </summary>
        public static int CompareVersions(string left, string right)
        {
            var leftSplit = SplitSemVer(left);
            var rightSplit = SplitSemVer(right);
            if (leftSplit == null || rightSplit == null) return 0;

            var (leftParts, leftPrerelease) = leftSplit.Value;
            var (rightParts, rightPrerelease) = rightSplit.Value;

            var length = Math.Max(leftParts.Length, rightParts.Length);
            for (var i = 0; i < length; i++)
            {
                var l = i < leftParts.Length ? leftParts[i] : 0;
                var r = i < rightParts.Length ? rightParts[i] : 0;
                if (l != r) return l.CompareTo(r);
            }

            bool leftHasPre = !string.IsNullOrEmpty(leftPrerelease);
            bool rightHasPre = !string.IsNullOrEmpty(rightPrerelease);

            if (!leftHasPre && rightHasPre) return 1;
            if (leftHasPre && !rightHasPre) return -1;
            if (leftHasPre && rightHasPre)
            {
                return ComparePrereleaseIdentifiers(leftPrerelease!, rightPrerelease!);
            }

            return 0;
        }

        private static (long[] Parts, string? Prerelease)? SplitSemVer(string version)
        {
            if (string.IsNullOrWhiteSpace(version)) return null;

            var clean = version.Trim().TrimStart('v', 'V');
            string? prerelease = null;

            var dashIdx = clean.IndexOf('-');
            var plusIdx = clean.IndexOf('+');
            var metaIdx = (dashIdx >= 0 && plusIdx >= 0) ? Math.Min(dashIdx, plusIdx) : Math.Max(dashIdx, plusIdx);

            if (metaIdx >= 0)
            {
                if (dashIdx >= 0 && (plusIdx < 0 || dashIdx < plusIdx))
                {
                    prerelease = plusIdx > dashIdx ? clean.Substring(dashIdx + 1, plusIdx - dashIdx - 1) : clean.Substring(dashIdx + 1);
                }
                clean = clean.Substring(0, metaIdx);
            }

            var raw = clean.Split('.', StringSplitOptions.RemoveEmptyEntries);
            if (raw.Length == 0) return null;

            var parts = new long[raw.Length];
            for (var i = 0; i < raw.Length; i++)
            {
                if (!long.TryParse(raw[i], out parts[i])) return null;
            }

            return (parts, prerelease);
        }

        private static int ComparePrereleaseIdentifiers(string left, string right)
        {
            var leftTokens = left.Split('.', StringSplitOptions.RemoveEmptyEntries);
            var rightTokens = right.Split('.', StringSplitOptions.RemoveEmptyEntries);
            var len = Math.Max(leftTokens.Length, rightTokens.Length);

            for (int i = 0; i < len; i++)
            {
                if (i >= leftTokens.Length) return -1;
                if (i >= rightTokens.Length) return 1;

                var lToken = leftTokens[i];
                var rToken = rightTokens[i];

                bool lIsNum = long.TryParse(lToken, out var lNum);
                bool rIsNum = long.TryParse(rToken, out var rNum);

                if (lIsNum && rIsNum)
                {
                    if (lNum != rNum) return lNum.CompareTo(rNum);
                }
                else if (lIsNum && !rIsNum)
                {
                    return -1;
                }
                else if (!lIsNum && rIsNum)
                {
                    return 1;
                }
                else
                {
                    var cmp = string.Compare(lToken, rToken, StringComparison.OrdinalIgnoreCase);
                    if (cmp != 0) return cmp;
                }
            }

            return 0;
        }
    }
